// Deterministic, offline AttoLang probe-ID generator. No guest runtime compiler.
import {createHash} from 'node:crypto';
import {readFileSync,writeFileSync} from 'node:fs';
import {resolve} from 'node:path';
import {fileURLToPath} from 'node:url';

const KINDS = new Set(['span','counter','gauge','instant']);
const NAME = /^[a-z][a-z0-9_]*(?:\.[a-z][a-z0-9_]*)*$/;
const MAX_PROBES = 4096;
const MAX_ID = 2147483647;

export function generate_perf_probes(input) {
  if (!input || input.schema !== 'atto.perf-probes.v1' || !Array.isArray(input.registry)) {
    throw new Error('PERF_SCHEMA: expected atto.perf-probes.v1 registry');
  }
  if (input.registry.length > MAX_PROBES) throw new Error('PERF_BUDGET: excessive probes');
  const ids = new Set(), names = new Set(), symbols = new Set();
  const rows = [];
  for (const p of input.registry) {
    if (!p || !Number.isSafeInteger(p.id) || p.id < 1 || p.id > MAX_ID)
      throw new Error('PERF_ID: must be positive int32');
    if (typeof p.name !== 'string' || !NAME.test(p.name) || p.name.length > 120)
      throw new Error('PERF_NAME: invalid static probe name');
    if (!KINDS.has(p.kind)) throw new Error('PERF_KIND: unknown event kind');
    if (!Number.isSafeInteger(p.sampling_divisor) || p.sampling_divisor < 1 || p.sampling_divisor > 65536)
      throw new Error('PERF_SAMPLE: sampling divisor out of range');
    const symbol = p.name.replaceAll('.', '_');
    if (ids.has(p.id) || names.has(p.name) || symbols.has(symbol))
      throw new Error('PERF_DUPLICATE: id/name/generated symbol collision');
    ids.add(p.id); names.add(p.name); symbols.add(symbol);
    rows.push({id:p.id,name:p.name,kind:p.kind,sampling_divisor:p.sampling_divisor,symbol});
  }
  rows.sort((a,b)=>a.id-b.id);
  const encoded = JSON.stringify(rows);
  const sha256 = createHash('sha256').update(encoded,'utf8').digest('hex');
  const source = [
    '// Generated by tools/generate-perf-probes.mjs. Build-time only; do not edit.',
    '// Schema: atto.perf-probes.v1; IDs are stable across AOT/JIT.',
    'define module PerfIds as',
    ...rows.map(row => '  pub fnc '+row.symbol+'() -> int { return '+row.id+'; }'),
    'end',''
  ].join('\n');
  const plan={schema:'atto.perf-probes-plan.v1',source_registry_sha256:sha256,
              runtime_jit_required:false,probe_count:rows.length,probes:rows};
  return {source,plan};
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (process.argv.length !== 5) {
    process.stderr.write('Usage: node tools/generate-perf-probes.mjs <registry.json> <PerfIds.atto> <probe-plan.json>\n');
    process.exitCode=2;
  } else {
    try {
      const input=JSON.parse(readFileSync(process.argv[2],'utf8'));
      const {source,plan}=generate_perf_probes(input);
      writeFileSync(process.argv[3],source,{flag:'w'});
      writeFileSync(process.argv[4],JSON.stringify(plan,null,2)+'\n',{flag:'w'});
    } catch(e) {
      process.stderr.write(String(e.message)+'\n');
      process.exitCode=1;
    }
  }
}
